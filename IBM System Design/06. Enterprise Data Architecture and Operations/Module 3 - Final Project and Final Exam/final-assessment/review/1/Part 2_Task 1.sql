SET NAMES utf8mb4;
DROP DATABASE IF EXISTS banque_oltp;
CREATE DATABASE banque_oltp CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE banque_oltp;

CREATE TABLE agence (
  agence_id   INT AUTO_INCREMENT PRIMARY KEY,
  code_agence VARCHAR(10) NOT NULL UNIQUE,
  nom         VARCHAR(60) NOT NULL,
  ville       VARCHAR(40) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE type_compte (
  type_compte_id INT AUTO_INCREMENT PRIMARY KEY,
  libelle        VARCHAR(40) NOT NULL UNIQUE,
  taux_interet   DECIMAL(5,2) NOT NULL DEFAULT 0,
  CONSTRAINT chk_taux_interet CHECK (taux_interet >= 0)
) ENGINE=InnoDB;

CREATE TABLE client (
  client_id      INT AUTO_INCREMENT PRIMARY KEY,
  nom            VARCHAR(50) NOT NULL,
  prenom         VARCHAR(50) NOT NULL,
  date_naissance DATE NOT NULL,
  cin            VARCHAR(18) NOT NULL UNIQUE,
  segment        VARCHAR(20) NOT NULL,
  CONSTRAINT chk_client_segment CHECK (segment IN ('Particulier','Professionnel','Entreprise'))
) ENGINE=InnoDB;

CREATE TABLE compte (
  compte_id      INT AUTO_INCREMENT PRIMARY KEY,
  agence_id      INT NOT NULL,
  type_compte_id INT NOT NULL,
  rib            VARCHAR(20) NOT NULL UNIQUE,
  solde          DECIMAL(15,2) NOT NULL DEFAULT 0,
  date_ouverture DATE NOT NULL,
  statut         VARCHAR(10) NOT NULL DEFAULT 'Actif',
  CONSTRAINT fk_compte_agence FOREIGN KEY (agence_id) REFERENCES agence(agence_id),
  CONSTRAINT fk_compte_type   FOREIGN KEY (type_compte_id) REFERENCES type_compte(type_compte_id),
  CONSTRAINT chk_compte_statut CHECK (statut IN ('Actif','Bloque','Cloture'))
) ENGINE=InnoDB;

CREATE TABLE titulaire (
  compte_id INT NOT NULL,
  client_id INT NOT NULL,
  role      VARCHAR(15) NOT NULL DEFAULT 'Titulaire',
  PRIMARY KEY (compte_id, client_id),
  CONSTRAINT fk_titulaire_compte FOREIGN KEY (compte_id) REFERENCES compte(compte_id),
  CONSTRAINT fk_titulaire_client FOREIGN KEY (client_id) REFERENCES client(client_id),
  CONSTRAINT chk_titulaire_role CHECK (role IN ('Titulaire','Co-titulaire','Mandataire'))
) ENGINE=InnoDB;

CREATE TABLE type_operation (
  type_operation_id INT AUTO_INCREMENT PRIMARY KEY,
  libelle           VARCHAR(40) NOT NULL UNIQUE,
  sens              CHAR(1) NOT NULL,
  CONSTRAINT chk_sens CHECK (sens IN ('D','C'))
) ENGINE=InnoDB;

CREATE TABLE operation (
  operation_id      BIGINT AUTO_INCREMENT PRIMARY KEY,
  compte_id         INT NOT NULL,
  type_operation_id INT NOT NULL,
  montant           DECIMAL(15,2) NOT NULL,
  date_operation    DATETIME NOT NULL,
  reference         VARCHAR(20) NOT NULL UNIQUE,
  CONSTRAINT fk_operation_compte FOREIGN KEY (compte_id) REFERENCES compte(compte_id),
  CONSTRAINT fk_operation_type   FOREIGN KEY (type_operation_id) REFERENCES type_operation(type_operation_id),
  CONSTRAINT chk_montant CHECK (montant > 0),
  KEY idx_operation_compte_date (compte_id, date_operation)
) ENGINE=InnoDB;

CREATE TABLE pret (
  pret_id     INT AUTO_INCREMENT PRIMARY KEY,
  client_id   INT NOT NULL,
  compte_id   INT NOT NULL,
  capital     DECIMAL(15,2) NOT NULL,
  taux        DECIMAL(5,2) NOT NULL,
  duree_mois  INT NOT NULL,
  date_octroi DATE NOT NULL,
  statut      VARCHAR(15) NOT NULL,
  CONSTRAINT fk_pret_client FOREIGN KEY (client_id) REFERENCES client(client_id),
  CONSTRAINT fk_pret_compte FOREIGN KEY (compte_id) REFERENCES compte(compte_id),
  CONSTRAINT chk_pret_capital CHECK (capital > 0),
  CONSTRAINT chk_pret_taux    CHECK (taux >= 0),
  CONSTRAINT chk_pret_duree   CHECK (duree_mois > 0),
  CONSTRAINT chk_pret_statut  CHECK (statut IN ('En cours','Rembourse','Impaye'))
) ENGINE=InnoDB;

